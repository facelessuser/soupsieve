"""
Generate `soupsieve/bidi.py` from the Unicode Character Database.

`:dir()` needs the bidirectional class of a character, but Python's `unicodedata` only knows
the Unicode version a given Python shipped with and has no class for unassigned code points.
Generating a table lets every Python version use the same, chosen, Unicode version.

Usage: `python tools/gen_bidi.py [version]`, where `version` is something like `18.0.0`, and is
`latest` by default. The per range defaults that this relies on are only provided by 15.0 and later.
"""
import os
import re
import sys
import textwrap
import urllib.error
import urllib.request

URL = 'https://www.unicode.org/Public/{}/ucd/extracted/DerivedBidiClass.txt'
URL_LATEST = 'https://www.unicode.org/Public/UCD/latest/ucd/extracted/DerivedBidiClass.txt'

OUTPUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'soupsieve', 'bidi.py')

RE_VERSION = re.compile(r'^# DerivedBidiClass-(\d+\.\d+\.\d+)\.txt')
RE_MISSING = re.compile(r'^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)', re.M)
RE_ENTRY = re.compile(r'^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)\s*#', re.M)

MAX_CODE_POINT = 0x10FFFF
WIDTH = 120

# Only the first strong character matters, so all that is needed is `L`, `R`, or neither (`N`).
STRONG_CLASSES = {
    'L': 'L',
    'R': 'R',
    'AL': 'R',
    'Left_To_Right': 'L',
    'Right_To_Left': 'R',
    'Arabic_Letter': 'R'
}

TEMPLATE = '''\
"""
Bidirectional text data for Unicode {version}.

Generated by `tools/gen_bidi.py`, do not edit.
"""

UNICODE_VERSION = '{version}'

# Each code point begins a run of characters that have the same direction.
STARTS: tuple[int, ...] = (
{starts}
)

# The direction of each run: `L` is left to right, `R` is right to left, and `N` is not a strong direction.
DIRECTIONS = (
{directions}
)
'''


def fetch(version: str) -> str:
    """Download the bidirectional class data."""

    url = URL_LATEST if version == 'latest' else URL.format(version)
    try:
        with urllib.request.urlopen(url) as response:
            return response.read().decode('utf-8')
    except urllib.error.HTTPError as e:
        raise SystemExit(f'Could not get {url}: {e}') from e


def parse(data: str) -> tuple[str, list[str]]:
    """Get the Unicode version, and the direction of every code point."""

    match = RE_VERSION.match(data)
    if match is None:
        raise SystemExit('Could not determine the Unicode version of the data')

    # Unassigned code points are not listed, only described by ranges with a default. These come first,
    # with the first being a default for everything. Later ranges override earlier ones.
    missing = RE_MISSING.findall(data)
    if len(missing) < 2:
        raise SystemExit(f'Unicode {match.group(1)} has no per range defaults, Unicode 15.0 or later is required')

    directions = ['N'] * (MAX_CODE_POINT + 1)
    for start, end, name in missing:
        first, last = int(start, 16), int(end, 16)
        directions[first:last + 1] = [STRONG_CLASSES.get(name, 'N')] * (last + 1 - first)

    # Anything listed has a specific class that overrides the defaults.
    for start, end, name in RE_ENTRY.findall(data):
        first, last = int(start, 16), int(end or start, 16)
        directions[first:last + 1] = [STRONG_CLASSES.get(name, 'N')] * (last + 1 - first)

    return match.group(1), directions


def get_runs(directions: list[str]) -> tuple[list[int], str]:
    """Reduce the direction of every code point to where each run starts and the direction of that run."""

    starts = []
    runs = []
    for code_point, direction in enumerate(directions):
        if not runs or runs[-1] != direction:
            starts.append(code_point)
            runs.append(direction)
    return starts, ''.join(runs)


def format_data(version: str, starts: list[int], directions: str) -> str:
    """Format the output module."""

    return TEMPLATE.format(
        version=version,
        starts=textwrap.fill(
            ', '.join(f'0x{start:04X}' for start in starts) + ',',
            WIDTH,
            initial_indent=' ' * 4,
            subsequent_indent=' ' * 4
        ),
        directions='\n'.join(
            f"    '{directions[i:i + WIDTH - 6]}'" for i in range(0, len(directions), WIDTH - 6)
        )
    )


def main() -> None:
    """Generate the module."""

    version, directions = parse(fetch(sys.argv[1] if len(sys.argv) > 1 else 'latest'))
    starts, runs = get_runs(directions)
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(format_data(version, starts, runs))
    print(f'Wrote {len(starts)} runs for Unicode {version} to {OUTPUT}')


if __name__ == '__main__':
    main()
